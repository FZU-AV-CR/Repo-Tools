"""
correct_jsons.py -- patch FRAM JSON metadata files generated by fram_make_json.py.

Applies a fixed set of corrections to every JSON file found under one or more
source directories:
  1. Normalise subject values (capitalisation, typos).
  2. Enforce the required abstract description text.
  3. Enforce the resource title on every related_resource entry.
  4. Fill or add the record URL identifier (derived from site + FITS filename).
  5. Set a uniform publication date throughout the JSON.

By default the script runs in preview mode and prints what it would change.
Pass --apply to write corrected copies.

Usage:
    python3 correct_jsons.py --source /data/json/cta-n/2019 --out /data/json/corrected \\
        --site cta-n --date 2026-11-01 --apply
"""

import argparse
import copy
import datetime
import json
import re
from pathlib import Path
from urllib.parse import quote


DESCRIPTION = (
    "This dataset contains observation data in the FITS format. "
    "The observation comes from a robotic telescope "
    "(Photometric Robotic Atmospheric Monitor - FRAM)."
)

RESOURCE_TITLE = "FRAM Robotic Telescopes Data Collection"

# Landing-page base URL. Currently targets the test environment;
# update to the production URL before a production run.
BASE_RECORD_URL = "https://test1.physics.du.cesnet.cz/fram/records"


def correct_dates(data, output_date: str):
    """Set metadata.publication_date to output_date.

    Only the publication_date field is updated. Observation dates stored under
    metadata.dates[].date (e.g. the Created date from DATE-OBS) are left
    unchanged — they carry scientific information and must not be overwritten.
    """
    metadata = data.get("metadata")
    if isinstance(metadata, dict):
        metadata["publication_date"] = output_date
    return data


def find_fits_filename(value):
    """Find a FITS filename or path anywhere in the JSON."""
    if isinstance(value, dict):
        for item in value.values():
            result = find_fits_filename(item)
            if result:
                return result

    elif isinstance(value, list):
        for item in value:
            result = find_fits_filename(item)
            if result:
                return result

    elif isinstance(value, str):
        normalized = value.strip().replace("\\", "/")
        filename = normalized.split("/")[-1].split("?")[0]

        if filename.lower().endswith((".fits", ".fit", ".fts")):
            return filename

    return None


def build_record_url(data, site):
    """Construct a record URL using the site and FITS filename."""
    fits_filename = find_fits_filename(data)

    if not fits_filename:
        return None

    fits_name = Path(fits_filename).stem

    # Remove a trailing -RA suffix if it is not part of the record ID.
    fits_name = re.sub(
        r"-RA$", "", fits_name, flags=re.IGNORECASE
    )

    if not fits_name:
        return None

    slug = f"{site}-{fits_name}"

    return f"{BASE_RECORD_URL}/{quote(slug, safe='-._')}"


def correct_identifier(data, site):
    """Fill a blank URL identifier or add one if none exists."""
    if not isinstance(data, dict):
        return

    metadata = data.get("metadata")
    if not isinstance(metadata, dict):
        return

    url = build_record_url(data, site)
    if not url:
        return

    identifiers = metadata.get("identifiers")

    if not isinstance(identifiers, list):
        identifiers = []
        metadata["identifiers"] = identifiers

    # Fill a blank URL identifier.
    for identifier in identifiers:
        if not isinstance(identifier, dict):
            continue

        if (
            identifier.get("scheme") == "url"
            and not str(
                identifier.get("identifier", "")
            ).strip()
        ):
            identifier["identifier"] = url
            return

    # Preserve an existing nonblank URL identifier.
    for identifier in identifiers:
        if (
            isinstance(identifier, dict)
            and identifier.get("scheme") == "url"
            and str(
                identifier.get("identifier", "")
            ).strip()
        ):
            return

    # Add a URL identifier if one does not exist.
    identifiers.append({
        "identifier": url,
        "scheme": "url",
    })


def correct_json(data, site, output_date: str):
    """Apply all required metadata corrections."""
    if not isinstance(data, dict):
        return correct_dates(data, output_date)

    metadata = data.get("metadata")

    if not isinstance(metadata, dict):
        return correct_dates(data, output_date)

    # 1. Correct subject values wherever they currently occur.
    subjects = metadata.get("subjects", [])

    if isinstance(subjects, list):
        for subject in subjects:
            if not isinstance(subject, dict):
                continue

            value = subject.get("subject")

            if isinstance(value, str):
                normalized = value.strip().casefold()

                if normalized == "fram":
                    subject["subject"] = "FRAM"

                elif normalized == (
                    "photometric robotic atmosperic monitor"
                ):
                    subject["subject"] = (
                        "Photometric robotic atmospheric monitor"
                    )

    # 2. Enforce the required abstract description.
    descriptions = metadata.get("additional_descriptions")

    if not isinstance(descriptions, list):
        descriptions = []
        metadata["additional_descriptions"] = descriptions

    abstract_found = False

    for description in descriptions:
        if not isinstance(description, dict):
            continue

        # Support the actual schema: {"type": {"id": "abstract"}}
        # Also tolerate the older description_type format.
        desc_type = description.get("type", {})
        if isinstance(desc_type, dict):
            type_id = desc_type.get("id", "")
        else:
            type_id = desc_type

        if not type_id:
            type_id = description.get("description_type", "")

        if isinstance(type_id, dict):
            type_id = type_id.get("id", "")

        if str(type_id).strip().casefold() == "abstract":
            description["description"] = DESCRIPTION
            abstract_found = True

    # Create an abstract entry if no abstract was present.
    if not abstract_found:
        descriptions.append({
            "lang": {"id": "ENG"},
            "type": {"id": "abstract"},
            "description": DESCRIPTION,
        })

    # 3. Enforce the resource title on every existing resource.
    resources = metadata.get("related_resources")

    if not isinstance(resources, list):
        resources = []
        metadata["related_resources"] = resources

    if resources:
        for resource in resources:
            if isinstance(resource, dict):
                resource["title"] = RESOURCE_TITLE
    else:
        # Create a resource entry if none exists.
        resources.append({
            "title": RESOURCE_TITLE,
        })

    # 4. Fill the dynamic record URL identifier.
    correct_identifier(data, site)

    # 5. Enforce the output date throughout the JSON.
    return correct_dates(data, output_date)


def main():
    today = datetime.date.today().isoformat()

    parser = argparse.ArgumentParser(
        description=(
            "Enforce FRAM JSON metadata values and save corrected "
            "copies while preserving the directory structure."
        )
    )
    parser.add_argument(
        "--source",
        action="append",
        metavar="DIR",
        required=True,
        help="Source directory to scan recursively for JSON files. "
             "Repeat to process multiple directories in one run.",
    )
    parser.add_argument(
        "--out",
        required=True,
        metavar="DIR",
        help="Output directory for corrected copies. "
             "The relative path beneath each --source directory is preserved.",
    )
    parser.add_argument(
        "--site",
        required=True,
        help="FRAM site name used when building record URLs (e.g. cta-n, auger, cta-s1).",
    )
    parser.add_argument(
        "--date",
        default=today,
        metavar="YYYY-MM-DD",
        help=f"Publication date written into every date field (default: today, {today}).",
    )
    parser.add_argument(
        "--apply",
        action="store_true",
        help="Write corrected copies. Without this flag, preview only.",
    )

    args = parser.parse_args()

    try:
        datetime.date.fromisoformat(args.date)
    except ValueError:
        parser.error(f"--date must be a valid date in YYYY-MM-DD format, got {args.date!r}")

    output_dir = Path(args.out).resolve()
    source_dirs = [Path(s).resolve() for s in args.source]
    site = args.site
    output_date = args.date

    scanned = 0
    changed = 0
    written = 0
    errors = 0
    skipped_no_fits = 0

    print(f"Site:              {site}")
    print(f"Publication date:  {output_date}")
    print(f"Output directory:  {output_dir}")
    print(f"Source directories:")
    for d in source_dirs:
        print(f"  {d}")
    print()

    for source_year_dir in source_dirs:
        if not source_year_dir.is_dir():
            print(f"WARNING: Directory not found: {source_year_dir}")
            continue

        for src in source_year_dir.rglob("*.json"):
            
            # Skip files located inside any directory named "bad".
            if any(part.casefold() == "bad" for part in src.parts):
                print(f"SKIPPED (bad directory): {src}")
                continue

            scanned += 1

            try:
                with src.open("r", encoding="utf-8-sig") as file:
                    original_data = json.load(file)

                corrected_data = correct_json(
                    copy.deepcopy(original_data),
                    site,
                    output_date,
                )

                if corrected_data == original_data:
                    continue

                # Preserve the relative path beneath the source directory.
                relative_path = src.relative_to(source_year_dir)
                dst = output_dir / relative_path

                changed += 1

                if args.apply:
                    dst.parent.mkdir(parents=True, exist_ok=True)

                    with dst.open("w", encoding="utf-8") as file:
                        json.dump(
                            corrected_data,
                            file,
                            ensure_ascii=False,
                            indent=2,
                        )
                        file.write("\n")

                    written += 1
                    print(f"UPDATED: {dst}")

                else:
                    print(f"WOULD UPDATE: {src}")
                    print(f"  Output: {dst}")

                    generated_url = build_record_url(
                        original_data, site
                    )

                    if generated_url:
                        print(f"  Record URL: {generated_url}")
                    else:
                        skipped_no_fits += 1
                        print(
                            "  WARNING: No FITS filename found; "
                            "URL identifier cannot be generated."
                        )

            except (
                OSError,
                json.JSONDecodeError,
                TypeError,
                ValueError,
            ) as exc:
                errors += 1
                print(f"ERROR: {src}: {exc}")

    print("\n--- Summary ---")
    print(f"JSON files scanned:          {scanned}")
    print(f"Files requiring corrections: {changed}")

    if args.apply:
        print(f"Corrected copies written:    {written}")
    else:
        print("Preview only: no files written.")
        print('Run with "--apply" to save corrected copies.')

    print(f"Files without generated URLs: {skipped_no_fits}")
    print(f"Errors:                      {errors}")


if __name__ == "__main__":
    main()

# Example:
# python3 correct_jsons.py \
#     --source /data/json/cta-n/2019 --source /data/json/cta-n/2020 \
#     --out /data/json/corrected --site cta-n --date 2026-11-01 --apply